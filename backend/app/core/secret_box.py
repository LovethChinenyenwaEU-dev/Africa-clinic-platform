"""Secrets kept in the database, encrypted with a key that is not (Week 12).

Used for the authenticator-app secrets: anyone holding one can make valid sign-in codes,
so a copied database or backup must not be enough. Each value is sealed with Fernet
(AES-128 in CBC mode with an HMAC-SHA256 check, from the `cryptography` library) and
stored as "enc:v1:<token>". The key lives only in the environment (DATA_ENCRYPTION_KEYS;
on Render, generated by Render).

Keys are long random strings, comma separated, newest first. The newest seals; every key
can open. To change the key: put the new one first, keep the old one after it, and
remove the old one only once every value has been sealed again (each value is resealed
the next time it is used).

A value without the "enc:v1:" mark was stored before Week 12 as plain text. It is still
read, and sealed the next time it is used, so no migration is needed.
"""
import base64
import hashlib

from cryptography.fernet import Fernet, InvalidToken, MultiFernet

from app.core.config import settings

PREFIX = "enc:v1:"
DEFAULT_DATA_KEY = "dev-only-data-key-change-me-before-real-use-0123456789"
SAFE_WITH_DEFAULT = ("development", "test")


class SecretUnreadableError(Exception):
    """A sealed value that no current key can open (wrong or removed key, or changed)."""


def _fernet(key: str) -> Fernet:
    # Fernet needs 32 bytes; the configured key is a long random string, so its SHA-256
    # gives exactly that.
    return Fernet(base64.urlsafe_b64encode(hashlib.sha256(key.encode()).digest()))


def _box() -> MultiFernet:
    keys = [key.strip() for key in settings.data_encryption_keys.split(",") if key.strip()]
    if not keys:
        if settings.environment not in SAFE_WITH_DEFAULT:
            raise RuntimeError(
                "DATA_ENCRYPTION_KEYS must be set before running outside development."
            )
        keys = [DEFAULT_DATA_KEY]
    return MultiFernet([_fernet(key) for key in keys])


def seal(plain: str) -> str:
    """Encrypt a value for the database."""
    return PREFIX + _box().encrypt(plain.encode()).decode()


def is_sealed(stored: str) -> bool:
    return stored.startswith(PREFIX)


def open_value(stored: str) -> str:
    """The plain value. A value from before Week 12 (no mark) is returned as it is."""
    if not is_sealed(stored):
        return stored
    try:
        return _box().decrypt(stored.removeprefix(PREFIX).encode()).decode()
    except InvalidToken:
        raise SecretUnreadableError(
            "A stored secret could not be opened with the current keys."
        ) from None


def reseal(stored: str) -> str:
    """The same value sealed with the newest key: for plain values from before Week 12,
    and for values sealed with an older key."""
    return seal(open_value(stored))
